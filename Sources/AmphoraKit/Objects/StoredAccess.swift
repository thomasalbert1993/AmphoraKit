import CoreData

/// Whether a `@Stored` property gets a setter.
public enum StoredAccess: Sendable {

    /// A getter only, the default: writes go through the storage property.
    case readonly

    /// A getter and a setter writing back to the storage property.
    case readWrite
}

/// The order a to-many `@Relationship` reads its objects in — in no particular order when
/// none is given, like the set Core Data keeps.
public enum RelationshipOrder: Sendable {

    /// Sorted by the target's `Comparable` conformance, which it then requires.
    case sorted
}

/// The filter a `@Relationship` reads its objects through — by default, the zombies, the
/// soft-deleted objects of a `SoftDeletable` target and the objects a `RelationshipFiltering`
/// target leaves out are removed.
public enum RelationshipFilter: Sendable {

    /// The zombies removed only: the soft-deleted objects and the ones the target filters out
    /// are read too.
    case unfiltered
}

/// How an `@Attribute` column compares in the queries `@Entity` generates — by default, a column
/// holding `Any` or stored as a collection (a transformable) is opaque, any other one comparable.
public enum AttributeComparability: Sendable {

    /// No equality member, no sort and no field: a column the store can't compare (a value stored
    /// in a transformable) or whose stored order isn't the value's. Its `Match` member stays, for
    /// the matches that need no comparison (`.isNil`).
    case opaque
}

/// The conversions the accessors generated by `@Stored` and `@Attribute` call.
///
/// The macro only sees syntax, so it never knows the stored type: it emits a call to `read` /
/// `write` and overload resolution picks the conversion from the stored and exposed types —
/// identity, raw value, `StorageConvertible` storage, zombie-safe relationship.
public enum StoredAccessor {

    // MARK: Reading

    /// Same type on both sides.
    @inlinable
    public static func read<T>(_ value: T) -> T {
        value
    }

    /// A `RawRepresentable` stored by its raw value.
    @inlinable
    public static func read<T: RawRepresentable>(_ raw: T.RawValue) -> T? {
        T(rawValue: raw)
    }

    /// A `RawRepresentable` stored by its raw value, with a fallback.
    @inlinable
    public static func read<T: RawRepresentable>(_ raw: T.RawValue, default fallback: T) -> T {
        T(rawValue: raw) ?? fallback
    }

    /// A `RawRepresentable` stored by an optional raw value.
    @inlinable
    public static func read<T: RawRepresentable>(_ raw: T.RawValue?) -> T? {
        raw.flatMap(T.init(rawValue:))
    }

    /// A `RawRepresentable` stored by an optional raw value, with a fallback.
    @inlinable
    public static func read<T: RawRepresentable>(_ raw: T.RawValue?, default fallback: T) -> T {
        raw.flatMap(T.init(rawValue:)) ?? fallback
    }

    /// A `StorageConvertible` stored by its storage.
    @inlinable
    public static func read<T: StorageConvertible>(_ storage: T.Storage) -> T? {
        T.decoded(from: storage)
    }

    /// A `StorageConvertible` stored by its storage, with a fallback.
    @inlinable
    public static func read<T: StorageConvertible>(_ storage: T.Storage, default fallback: T) -> T {
        T.decoded(from: storage) ?? fallback
    }

    /// A `StorageConvertible` stored by an optional storage.
    @inlinable
    public static func read<T: StorageConvertible>(_ storage: T.Storage?) -> T? {
        storage.flatMap(T.decoded(from:))
    }

    /// A `StorageConvertible` stored by an optional storage, with a fallback.
    @inlinable
    public static func read<T: StorageConvertible>(_ storage: T.Storage?, default fallback: T) -> T {
        storage.flatMap(T.decoded(from:)) ?? fallback
    }

    /// Any value with a fallback for `nil`.
    @inlinable
    public static func read<T>(_ value: T?, default fallback: T) -> T {
        value ?? fallback
    }

    /// A collection over an optional column, empty for `nil`: an array or a set needs no `default:`.
    @inlinable
    public static func read<T: ExpressibleByArrayLiteral>(_ value: T?) -> T {
        value ?? []
    }

    /// A dictionary over an optional column, empty for `nil`.
    @inlinable
    public static func read<T: ExpressibleByDictionaryLiteral>(_ value: T?) -> T {
        value ?? [:]
    }

    /// An `InfallibleStorageConvertible` stored by its storage, which always decodes.
    @inlinable
    public static func read<T: InfallibleStorageConvertible>(_ storage: T.Storage) -> T {
        T.decoded(from: storage)
    }

    /// An `EmptyStorageConvertible` over an optional storage, empty for `nil` or an unreadable one.
    @inlinable
    public static func read<T: EmptyStorageConvertible>(_ storage: T.Storage?) -> T {
        storage.flatMap(T.decoded(from:)) ?? T()
    }

    /// A to-one relationship, `nil` when the object is a zombie.
    @inlinable
    public static func read<T: DatabaseObject>(_ object: T?) -> T? {
        object?.nilIfZombie
    }

    /// A to-one relationship to a `SoftDeletable`, `nil` when the object is a zombie or deleted.
    @inlinable
    public static func read<T: SoftDeletable>(_ object: T?) -> T? {
        object?.nilIfZombie?.nilIfSoftDeleted
    }

    /// A to-one relationship to a `RelationshipFiltering`, `nil` when the object is a zombie or
    /// filtered out.
    @inlinable
    public static func read<T: RelationshipFiltering>(_ object: T?) -> T? {
        object?.nilIfZombie.flatMap { $0.isReadThroughToOneRelationships ? $0 : nil }
    }

    /// A to-one relationship to a `SoftDeletable` `RelationshipFiltering`, `nil` when the object
    /// is a zombie, deleted or filtered out.
    @inlinable
    public static func read<T: SoftDeletable & RelationshipFiltering>(_ object: T?) -> T? {
        object?.nilIfZombie?.nilIfSoftDeleted.flatMap { $0.isReadThroughToOneRelationships ? $0 : nil }
    }

    /// A to-one relationship declared `.unfiltered`, `nil` when the object is a zombie only.
    @inlinable
    public static func readUnfiltered<T: DatabaseObject>(_ object: T?) -> T? {
        object?.nilIfZombie
    }

    /// A to-many relationship as an array, zombies removed.
    @inlinable
    public static func read<T: DatabaseObject>(_ objects: Set<T>) -> [T] {
        objects.removingZombies()
    }

    /// A to-many relationship to a `SoftDeletable`, zombies and deleted objects removed.
    @inlinable
    public static func read<T: SoftDeletable>(_ objects: Set<T>) -> [T] {
        objects.removingZombies().removingSoftDeleted()
    }

    /// A to-many relationship to a `RelationshipFiltering`, zombies and filtered out objects
    /// removed.
    @inlinable
    public static func read<T: RelationshipFiltering>(_ objects: Set<T>) -> [T] {
        objects.removingZombies().filter(\.isReadThroughToManyRelationships)
    }

    /// A to-many relationship to a `SoftDeletable` `RelationshipFiltering`, zombies, deleted and
    /// filtered out objects removed.
    @inlinable
    public static func read<T: SoftDeletable & RelationshipFiltering>(_ objects: Set<T>) -> [T] {
        objects.removingZombies().removingSoftDeleted().filter(\.isReadThroughToManyRelationships)
    }

    /// A to-many relationship declared `.unfiltered`, zombies removed only.
    @inlinable
    public static func readUnfiltered<T: DatabaseObject>(_ objects: Set<T>) -> [T] {
        objects.removingZombies()
    }

    /// A to-many relationship declared `.sorted`, zombies removed, by the target's order.
    @inlinable
    public static func readSorted<T: DatabaseObject & Comparable>(_ objects: Set<T>) -> [T] {
        read(objects).sorted()
    }

    /// A to-many relationship to a `SoftDeletable` declared `.sorted`, zombies and deleted
    /// objects removed, by the target's order.
    @inlinable
    public static func readSorted<T: SoftDeletable & Comparable>(_ objects: Set<T>) -> [T] {
        read(objects).sorted()
    }

    /// A to-many relationship to a `RelationshipFiltering` declared `.sorted`, zombies and
    /// filtered out objects removed, by the target's order.
    @inlinable
    public static func readSorted<T: RelationshipFiltering & Comparable>(_ objects: Set<T>) -> [T] {
        read(objects).sorted()
    }

    /// A to-many relationship to a `SoftDeletable` `RelationshipFiltering` declared `.sorted`,
    /// zombies, deleted and filtered out objects removed, by the target's order.
    @inlinable
    public static func readSorted<T: SoftDeletable & RelationshipFiltering & Comparable>(_ objects: Set<T>) -> [T] {
        read(objects).sorted()
    }

    /// A to-many relationship declared `.sorted` and `.unfiltered`, zombies removed only, by the
    /// target's order.
    @inlinable
    public static func readSortedUnfiltered<T: DatabaseObject & Comparable>(_ objects: Set<T>) -> [T] {
        objects.removingZombies().sorted()
    }

    /// A type both `RawRepresentable` and `StorageConvertible` is stored by its storage: the raw
    /// value is its display form.
    @inlinable
    public static func read<T: RawRepresentable & StorageConvertible>(_ storage: T.Storage) -> T? {
        T.decoded(from: storage)
    }

    /// A type both `RawRepresentable` and `StorageConvertible`, stored by an optional storage.
    @inlinable
    public static func read<T: RawRepresentable & StorageConvertible>(_ storage: T.Storage?) -> T? {
        storage.flatMap(T.decoded(from:))
    }

    /// A type both `RawRepresentable` and `StorageConvertible`, with a fallback.
    @inlinable
    public static func read<T: RawRepresentable & StorageConvertible>(_ storage: T.Storage?, default fallback: T) -> T {
        storage.flatMap(T.decoded(from:)) ?? fallback
    }

    /// An array of `RawRepresentable` stored by raw values, the undecodable ones dropped.
    @inlinable
    public static func read<T: RawRepresentable>(_ raws: [T.RawValue]) -> [T] {
        raws.compactMap(T.init(rawValue:))
    }

    /// An optional array of `RawRepresentable` stored by raw values.
    @inlinable
    public static func read<T: RawRepresentable>(_ raws: [T.RawValue]?) -> [T]? {
        raws.map { $0.compactMap(T.init(rawValue:)) }
    }

    /// An array of `RawRepresentable` over an optional column of raw values, empty for `nil`.
    @inlinable
    public static func read<T: RawRepresentable>(_ raws: [T.RawValue]?) -> [T] {
        (raws ?? []).compactMap(T.init(rawValue:))
    }

    /// A set of `RawRepresentable` stored by raw values, the undecodable ones dropped.
    @inlinable
    public static func read<T: RawRepresentable & Hashable>(_ raws: Set<T.RawValue>) -> Set<T> {
        Set(raws.compactMap(T.init(rawValue:)))
    }

    /// An optional set of `RawRepresentable` stored by raw values.
    @inlinable
    public static func read<T: RawRepresentable & Hashable>(_ raws: Set<T.RawValue>?) -> Set<T>? {
        raws.map { Set($0.compactMap(T.init(rawValue:))) }
    }

    /// A set of `RawRepresentable` over an optional column of raw values, empty for `nil`.
    @inlinable
    public static func read<T: RawRepresentable & Hashable>(_ raws: Set<T.RawValue>?) -> Set<T> {
        Set((raws ?? []).compactMap(T.init(rawValue:)))
    }

    /// An integer stored in another width, `Int` over an `Int32` column. Saturates out of range.
    @inlinable
    public static func read<T: BinaryInteger, Stored: BinaryInteger>(_ stored: Stored) -> T {
        T(clamping: stored)
    }

    /// An integer stored in another width, optional.
    @inlinable
    public static func read<T: BinaryInteger, Stored: BinaryInteger>(_ stored: Stored?) -> T? {
        stored.map(T.init(clamping:))
    }

    /// A floating-point value stored in another precision.
    @inlinable
    public static func read<T: BinaryFloatingPoint, Stored: BinaryFloatingPoint>(_ stored: Stored) -> T {
        T(stored)
    }

    /// A `RawRepresentable` with an integer raw value, stored in another integer width. Disfavored:
    /// in the raw value's own width, the plain raw value overload applies.
    @inlinable
    @_disfavoredOverload
    public static func read<T: RawRepresentable, Stored: BinaryInteger>(_ stored: Stored) -> T? where T.RawValue: BinaryInteger {
        T(rawValue: T.RawValue(clamping: stored))
    }

    /// A `RawRepresentable` with an integer raw value, stored in another integer width, with a fallback.
    @inlinable
    @_disfavoredOverload
    public static func read<T: RawRepresentable, Stored: BinaryInteger>(_ stored: Stored, default fallback: T) -> T where T.RawValue: BinaryInteger {
        T(rawValue: T.RawValue(clamping: stored)) ?? fallback
    }

    // MARK: Writing

    /// Same type on both sides.
    @inlinable
    public static func write<T>(_ value: T) -> T {
        value
    }

    /// A `RawRepresentable` written by its raw value.
    @inlinable
    public static func write<T: RawRepresentable>(_ value: T) -> T.RawValue {
        value.rawValue
    }

    /// An optional `RawRepresentable` written by its raw value.
    @inlinable
    public static func write<T: RawRepresentable>(_ value: T?) -> T.RawValue? {
        value?.rawValue
    }

    /// A `StorageConvertible` written by its storage.
    @inlinable
    public static func write<T: StorageConvertible>(_ value: T) -> T.Storage {
        value.storage
    }

    /// An optional `StorageConvertible` written by its storage.
    @inlinable
    public static func write<T: StorageConvertible>(_ value: T?) -> T.Storage? {
        value?.storage
    }

    /// An optional `NilStorageConvertible` written to a non-optional column, `nil` as its
    /// `nilStorage`.
    @inlinable
    public static func write<T: NilStorageConvertible>(_ value: T?) -> T.Storage {
        value?.storage ?? T.nilStorage
    }

    /// An `EmptyStorageConvertible` written to its optional column: wins over the plain and the
    /// optional `StorageConvertible` writes, which would both match.
    @inlinable
    public static func write<T: EmptyStorageConvertible>(_ value: T) -> T.Storage? {
        value.storage
    }

    /// A to-many relationship written from an array.
    @inlinable
    public static func write<T: DatabaseObject>(_ objects: [T]) -> Set<T> {
        Set(objects)
    }

    /// A type both `RawRepresentable` and `StorageConvertible`, written by its storage.
    @inlinable
    public static func write<T: RawRepresentable & StorageConvertible>(_ value: T) -> T.Storage {
        value.storage
    }

    /// An optional type both `RawRepresentable` and `StorageConvertible`, written by its storage.
    @inlinable
    public static func write<T: RawRepresentable & StorageConvertible>(_ value: T?) -> T.Storage? {
        value?.storage
    }

    /// An array of `RawRepresentable` written by raw values.
    @inlinable
    public static func write<T: RawRepresentable>(_ values: [T]) -> [T.RawValue] {
        values.map(\.rawValue)
    }

    /// An optional array of `RawRepresentable` written by raw values.
    @inlinable
    @_disfavoredOverload
    public static func write<T: RawRepresentable>(_ values: [T]?) -> [T.RawValue]? {
        values.map { $0.map(\.rawValue) }
    }

    /// A set of `RawRepresentable` written by raw values.
    @inlinable
    public static func write<T: RawRepresentable & Hashable>(_ values: Set<T>) -> Set<T.RawValue> where T.RawValue: Hashable {
        Set(values.map(\.rawValue))
    }

    /// An optional set of `RawRepresentable` written by raw values.
    @inlinable
    @_disfavoredOverload
    public static func write<T: RawRepresentable & Hashable>(_ values: Set<T>?) -> Set<T.RawValue>? where T.RawValue: Hashable {
        values.map { Set($0.map(\.rawValue)) }
    }

    /// An integer written in the storage width. Saturates out of range rather than trapping.
    @inlinable
    public static func write<Stored: BinaryInteger, T: BinaryInteger>(_ value: T) -> Stored {
        Stored(clamping: value)
    }

    /// An optional integer written in the storage width.
    @inlinable
    public static func write<Stored: BinaryInteger, T: BinaryInteger>(_ value: T?) -> Stored? {
        value.map(Stored.init(clamping:))
    }

    /// A floating-point value written in the storage precision.
    @inlinable
    public static func write<Stored: BinaryFloatingPoint, T: BinaryFloatingPoint>(_ value: T) -> Stored {
        Stored(value)
    }

    /// A `RawRepresentable` with an integer raw value, written in the storage width.
    @inlinable
    @_disfavoredOverload
    public static func write<Stored: BinaryInteger, T: RawRepresentable>(_ value: T) -> Stored where T.RawValue: BinaryInteger {
        Stored(clamping: value.rawValue)
    }
}
