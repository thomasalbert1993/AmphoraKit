                        .init(key: "a_pinned")
                    }
                    /// The stored form of `kind`.
                    public static var kind: AmphoraKit.Column<Note, String> {
                        .init(key: "a_kind")
                    }
                    /// The `cue` relationship.
                    public static var cue: AmphoraKit.Column<Note, Cue?> {
                        .init(key: "r_cue")
                    }
                    /// The `tags` relationship.
                    public static var tags: AmphoraKit.Column<Note, Set<Tag>> {
                        .init(key: "r_tags")
                    }
                }

                /// The attributes and relationships of `Note` as stored, generated by `@Entity`: the raw
                /// value of a coded or defaulted column, a relationship as Core Data holds it.
                public struct StoredValues {
                    /// The object read.
                    let object: Note
                    /// The stored form of `id`.
                    public var id: String {
                        object.a_id
                    }
                    /// The stored form of `text`.
                    public var text: String {
                        object.a_text
                    }
                    /// Whether the note is pinned.
                    public var isPinned: Bool {
                        object.a_pinned
                    }
                    /// The stored form of `kind`.
                    public var kind: String {
                        object.a_kind
                    }
                    /// The `cue` relationship as stored, zombies included.
                    public var cue: Cue? {
                        object.r_cue
                    }
                    /// The `tags` relationship as stored, zombies included.
                    public var tags: Set<Tag> {
                        object.r_tags
                    }
                }

                /// The attributes and relationships as stored, for the code that copies or compares them as is.
                public var stored: StoredValues {
                    StoredValues(object: self)
                }

                /// The `id` field, for the expression form of the queries.
                public static var id: AmphoraKit.Field<Note, String> {
                    .init(key: "a_id")
                }

                /// The `text` field, for the expression form of the queries.
                public static var text: AmphoraKit.Field<Note, String> {
                    .init(key: "a_text")
                }

                /// Whether the note is pinned.
                public static var isPinned: AmphoraKit.Field<Note, Bool> {
                    .init(key: "a_pinned")
                }

                /// The `kind` field, for the expression form of the queries.
                public static var kind: AmphoraKit.Field<Note, Kind> {
                    .init(key: "a_kind")
                }

                /// The `cue` field, for the expression form of the queries.
                public static var cue: AmphoraKit.Field<Note, Cue?> {
                    .init(key: "r_cue")
                }

                /// The `tags` field, for the expression form of the queries.
                public static var tags: AmphoraKit.Field<Note, Set<Tag>> {
                    .init(key: "r_tags")
                }

                /// The value of `a_text`.
                public var text: String {
                    a_text
                }

                /// The value of `r_cue`, `nil` when it is a zombie.
                public var cue: Cue? {
                    r_cue?.nilIfZombie
                }

                /// The objects of `r_tags`, zombies removed.
                public var tags: [Tag] {
                    r_tags.removingZombies()
                }
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Entity' skips 'r_legacy': declare it as 'Set<Target>' to query it", line: 10, column: 37, severity: .warning)
