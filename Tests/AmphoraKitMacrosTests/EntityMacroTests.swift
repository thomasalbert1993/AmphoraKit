import XCTest
import SwiftSyntaxMacros
import SwiftSyntaxMacrosTestSupport
import AmphoraKitMacrosPlugin

final class EntityMacroTests: XCTestCase {

    private let macros: [String: any Macro.Type] = ["Entity": EntityMacro.self, "Stored": StoredMacro.self, "StorageOnly": StorageOnlyMacro.self]

    func testPrefixedEntity() {
        assertMacroExpansion(
            """
            @Entity(attributePrefix: "a_", relationshipPrefix: "r_")
            public final class Note: NSManagedObject, IdentifiableDatabaseObject {
                @NSManaged public var a_id: String
                @NSManaged public var a_text: String
                @NSManaged public var a_pinned: Bool
                @NSManaged public var a_kind: String
                @StorageOnly @NSManaged public var a_shapeVersion: Int64
                @NSManaged public var r_cue: Cue?
                @NSManaged public var r_tags: Set<Tag>
                @NSManaged public var r_legacy: NSSet

                public var id: String { a_id }

                /// Whether the note is pinned.
                @Stored(\\.a_pinned) public var isPinned: Bool
                @Stored(\\.a_kind, default: Kind.note) public var kind: Kind
            }
            """,
            expandedSource: """
            public final class Note: NSManagedObject, IdentifiableDatabaseObject {
                @NSManaged public var a_id: String
                @NSManaged public var a_text: String
                @NSManaged public var a_pinned: Bool
                @NSManaged public var a_kind: String
                @NSManaged public var a_shapeVersion: Int64
                @NSManaged public var r_cue: Cue?
                @NSManaged public var r_tags: Set<Tag>
                @NSManaged public var r_legacy: NSSet

                public var id: String { a_id }

                /// Whether the note is pinned.
                public var isPinned: Bool {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_pinned)
                    }
                }
                public var kind: Kind {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_kind, default: Kind.note)
                    }
                }

                /// The typed predicate of `Note`, generated by `@Entity`.
                public struct Query: AmphoraKit.EntityQuery {
                    public let expression: AmphoraKit.QueryExpression<Note>
                    public init(_ expression: AmphoraKit.QueryExpression<Note>) {
                        self.expression = expression
                    }
                    public static func id(_ match: AmphoraKit.Match<String>) -> Query {
                        .init(.match("a_id", match))
                    }
                    public static func id(_ value: String) -> Query {
                        .id(.equal(value))
                    }
                    public static func text(_ match: AmphoraKit.Match<String>) -> Query {
                        .init(.match("a_text", match))
                    }
                    public static func text(_ value: String) -> Query {
                        .text(.equal(value))
                    }
                    /// Whether the note is pinned.
                    public static func isPinned(_ match: AmphoraKit.Match<Bool>) -> Query {
                        .init(.match("a_pinned", match))
                    }
                    /// Whether the note is pinned.
                    public static func isPinned(_ value: Bool) -> Query {
                        .isPinned(.equal(value))
                    }
                    public static func kind(_ match: AmphoraKit.Match<Kind>) -> Query {
                        .init(.match("a_kind", match))
                    }
                    public static func kind(_ value: Kind) -> Query {
                        .kind(.equal(value))
                    }
                    public static func cue(_ match: AmphoraKit.Match<Cue?>) -> Query {
                        .init(.match("r_cue", match))
                    }
                    public static func cue(_ query: Cue.Query) -> Query {
                        .init(.relation("r_cue", query.expression))
                    }
                    public static func tags(_ match: AmphoraKit.CollectionMatch<Tag>) -> Query {
                        .init(.collection("r_tags", match))
                    }
                }

                /// The typed sort descriptor of `Note`, generated by `@Entity`.
                public struct Sort: AmphoraKit.EntitySort {
                    public let expression: AmphoraKit.SortExpression<Note>
                    public init(_ expression: AmphoraKit.SortExpression<Note>) {
                        self.expression = expression
                    }
                    public static var id: Sort {
                        .init(key: "a_id")
                    }
                    public static var text: Sort {
                        .init(key: "a_text")
                    }
                    /// Whether the note is pinned.
                    public static var isPinned: Sort {
                        .init(key: "a_pinned")
                    }
                    public static var kind: Sort {
                        .init(key: "a_kind")
                    }
                }

                /// The `id` field, for the expression form of the queries.
                public static var id: AmphoraKit.Field<Note, String> {
                    .init(key: "a_id")
                }

                /// The `text` field, for the expression form of the queries.
                public static var text: AmphoraKit.Field<Note, String> {
                    .init(key: "a_text")
                }

                /// Whether the note is pinned.
                public static var isPinned: AmphoraKit.Field<Note, Bool> {
                    .init(key: "a_pinned")
                }

                /// The `kind` field, for the expression form of the queries.
                public static var kind: AmphoraKit.Field<Note, Kind> {
                    .init(key: "a_kind")
                }

                /// The `cue` field, for the expression form of the queries.
                public static var cue: AmphoraKit.Field<Note, Cue?> {
                    .init(key: "r_cue")
                }

                /// The value of `a_text`.
                public var text: String {
                    a_text
                }

                /// The value of `r_cue`, `nil` when it is a zombie.
                public var cue: Cue? {
                    r_cue?.nilIfZombie
                }

                /// The objects of `r_tags`, zombies removed.
                public var tags: [Tag] {
                    r_tags.removingZombies()
                }
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Entity' skips 'r_legacy': declare it as 'Set<Target>' to query it", line: 10, column: 37, severity: .warning)
            ],
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testUnprefixedEntityKeepsHandWrittenTypesAndSkipsCollidingNames() {
        assertMacroExpansion(
            """
            @Entity
            final class Item: NSManagedObject {
                @NSManaged var name: String
                @NSManaged var children: Set<Item>
                static var name: String { "Item" }

                struct Sort: EntitySort {
                    let expression: SortExpression<Item>
                    init(_ expression: SortExpression<Item>) { self.expression = expression }
                }
            }
            """,
            expandedSource: """
            final class Item: NSManagedObject {
                @NSManaged var name: String
                @NSManaged var children: Set<Item>
                static var name: String { "Item" }

                struct Sort: EntitySort {
                    let expression: SortExpression<Item>
                    init(_ expression: SortExpression<Item>) { self.expression = expression }
                }

                /// The typed predicate of `Item`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<Item>
                    init(_ expression: AmphoraKit.QueryExpression<Item>) {
                        self.expression = expression
                    }
                    static func name(_ match: AmphoraKit.Match<String>) -> Query {
                        .init(.match("name", match))
                    }
                    static func name(_ value: String) -> Query {
                        .name(.equal(value))
                    }
                    static func children(_ match: AmphoraKit.CollectionMatch<Item>) -> Query {
                        .init(.collection("children", match))
                    }
                }
            }
            """,
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

