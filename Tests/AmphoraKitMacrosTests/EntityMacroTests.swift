            final class Tag: NSManagedObject {
                @NSManaged var a_name: String
            }
            """,
            expandedSource: """
            final class Tag: NSManagedObject {
                @NSManaged var a_name: String

                /// The typed predicate of `Tag`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<Tag>
                    init(_ expression: AmphoraKit.QueryExpression<Tag>) {
                        self.expression = expression
                    }
                    static func name(_ match: AmphoraKit.Match<String>) -> Query {
                        .init(.match("a_name", match))
                    }
                    static func name(_ value: String) -> Query {
                        .name(.equal(value))
                    }
                }

                /// The typed sort descriptor of `Tag`, generated by `@Entity`.
                struct Sort: AmphoraKit.EntitySort {
                    let expression: AmphoraKit.SortExpression<Tag>
                    init(_ expression: AmphoraKit.SortExpression<Tag>) {
                        self.expression = expression
                    }
                    static var name: Sort {
                        .init(key: "a_name")
                    }
                }

                /// The `name` field, for the expression form of the queries.
                static var name: AmphoraKit.Field<Tag, String> {
                    .init(key: "a_name")
                }
            }
            """,
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testPrefixedSetAttributeIsAnAttribute() {
        assertMacroExpansion(
            """
            @Entity(attributePrefix: "a_", relationshipPrefix: "r_", generatesAccessors: false)
            final class View: NSManagedObject {
                @NSManaged var a_keys: Set<String>
            }
            """,
            expandedSource: """
            final class View: NSManagedObject {
                @NSManaged var a_keys: Set<String>

                /// The typed predicate of `View`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<View>
                    init(_ expression: AmphoraKit.QueryExpression<View>) {
                        self.expression = expression
                    }
                    static func keys(_ match: AmphoraKit.Match<Set<String>>) -> Query {
                        .init(.match("a_keys", match))
                    }
                    static func keys(_ value: Set<String>) -> Query {
                        .keys(.equal(value))
                    }
                }

                /// The typed sort descriptor of `View`, generated by `@Entity`.
                struct Sort: AmphoraKit.EntitySort {
                    let expression: AmphoraKit.SortExpression<View>
                    init(_ expression: AmphoraKit.SortExpression<View>) {
                        self.expression = expression
                    }
                    static var keys: Sort {
                        .init(key: "a_keys")
                    }
                }

                /// The `keys` field, for the expression form of the queries.
                static var keys: AmphoraKit.Field<View, Set<String>> {
                    .init(key: "a_keys")
                }
            }
            """,
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testRejectsStruct() {
        assertMacroExpansion(
            """
            @Entity
            struct Item {
            }
            """,
            expandedSource: """
            struct Item {
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Entity' can only be applied to an NSManagedObject subclass", line: 1, column: 1)
            ],
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }
}
