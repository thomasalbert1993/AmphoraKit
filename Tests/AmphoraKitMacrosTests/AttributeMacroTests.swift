                    }
                }

                /// The attributes and relationships of `Shot` in their stored form, generated by `@Entity`.
                enum Columns {
                }

                /// The attributes and relationships of `Shot` as stored, generated by `@Entity`: the raw
                /// value of a coded or defaulted column, a relationship as Core Data holds it.
