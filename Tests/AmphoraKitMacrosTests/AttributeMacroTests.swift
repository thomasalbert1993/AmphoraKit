import XCTest
import SwiftSyntaxMacros
import SwiftSyntaxMacrosTestSupport
import SwiftSyntax
import SwiftParser
import SwiftSyntaxMacroExpansion
import AmphoraKitMacrosPlugin

final class AttributeMacroTests: XCTestCase {

    private let macros: [String: any Macro.Type] = [
        "Entity": EntityMacro.self,
        "Attribute": AttributeMacro.self,
        "Relationship": RelationshipMacro.self
    ]

    func testEntityDeclaresTheStorageAndTheMacrosTheAccessors() {
        assertMacroExpansion(
            """
            @Entity(attributePrefix: "a_", relationshipPrefix: "r_")
            final class Shot: NSManagedObject {
                /// The position.
                @Attribute("a_sortOrder", storeAs: Int32.self, access: .readWrite) var order: Int
                @Attribute(storeAs: String.self, default: Kind.wide) var kind: Kind
                @Relationship var reel: Reel?
                @Relationship var takes: [Take]
            }
            """,
            expandedSource: """
            final class Shot: NSManagedObject {
                /// The position.
                var order: Int {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_sortOrder)
                    }
                    set {
                        self.a_sortOrder = AmphoraKit.StoredAccessor.write(newValue)
                    }
                }
                var kind: Kind {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_kind, default: Kind.wide)
                    }
                }
                var reel: Reel? {
                    get {
                        AmphoraKit.StoredAccessor.read(self.r_reel)
                    }
                }
                var takes: [Take] {
                    get {
                        AmphoraKit.StoredAccessor.read(self.r_takes)
                    }
                }

                @NSManaged var a_sortOrder: Int32

                @NSManaged var a_kind: String

                @NSManaged var r_reel: Reel?

                @NSManaged var r_takes: Set<Take>

                /// The typed predicate of `Shot`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<Shot>
                    init(_ expression: AmphoraKit.QueryExpression<Shot>) {
                        self.expression = expression
                    }
                    /// The position.
                    static func order(_ match: AmphoraKit.Match<Int>) -> Query {
                        .init(.match("a_sortOrder", match))
                    }
                    /// The position.
                    static func order(_ value: Int) -> Query {
                        .order(.equal(value))
                    }
                    static func kind(_ match: AmphoraKit.Match<Kind>) -> Query {
                        .init(.match("a_kind", match))
                    }
                    static func kind(_ value: Kind) -> Query {
                        .kind(.equal(value))
                    }
                    static func reel(_ match: AmphoraKit.Match<Reel?>) -> Query {
                        .init(.match("r_reel", match))
                    }
                    static func reel(_ query: Reel.Query) -> Query {
                        .init(.relation("r_reel", query.expression))
                    }
                    static func takes(_ match: AmphoraKit.CollectionMatch<Take>) -> Query {
                        .init(.collection("r_takes", match))
                    }
                }

                /// The typed sort descriptor of `Shot`, generated by `@Entity`.
                struct Sort: AmphoraKit.EntitySort {
                    let expression: AmphoraKit.SortExpression<Shot>
                    init(_ expression: AmphoraKit.SortExpression<Shot>) {
                        self.expression = expression
                    }
                    /// The position.
                    static var order: Sort {
                        .init(key: "a_sortOrder")
                    }
                    static var kind: Sort {
                        .init(key: "a_kind")
                    }
                }

                /// The typed attribute values of `Shot`, for batch requests too, generated by `@Entity`.
                struct AttributeAssignment: AmphoraKit.EntityAttributeAssignment {
                    typealias Root = Shot
                    let storageKey: String
                    let storageValue: Any?
                    init(storageKey: String, storageValue: Any?) {
                        self.storageKey = storageKey
                        self.storageValue = storageValue
                    }
                    /// The stored form of `order`, written as is.
                    static func order(stored value: Int32) -> AttributeAssignment {
                        .init(storageKey: "a_sortOrder", storageValue: value)
                    }
                    /// The position.
                    static func order(_ value: Int) -> AttributeAssignment {
                        .init(storageKey: "a_sortOrder", storageValue: AmphoraKit.StoredAccessor.write(value) as Int32)
                    }
                    /// The stored form of `kind`, written as is.
                    static func kind(stored value: String) -> AttributeAssignment {
                        .init(storageKey: "a_kind", storageValue: value)
                    }
                    static func kind(_ value: Kind) -> AttributeAssignment {
                        .init(storageKey: "a_kind", storageValue: AmphoraKit.StoredAccessor.write(value) as String)
                    }
                }

                /// The typed attribute and relationship values of `Shot` written on one object, generated by `@Entity`.
                struct Assignment: AmphoraKit.EntityAssignment {
                    typealias Root = Shot
                    let storageKey: String
                    let storageValue: Any?
                    init(storageKey: String, storageValue: Any?) {
                        self.storageKey = storageKey
                        self.storageValue = storageValue
                    }
                    /// The stored form of `order`, written as is.
                    static func order(stored value: Int32) -> Assignment {
                        .init(AttributeAssignment.order(stored: value))
                    }
                    /// The position.
                    static func order(_ value: Int) -> Assignment {
                        .init(AttributeAssignment.order(value))
                    }
                    /// The stored form of `kind`, written as is.
                    static func kind(stored value: String) -> Assignment {
                        .init(AttributeAssignment.kind(stored: value))
                    }
                    static func kind(_ value: Kind) -> Assignment {
                        .init(AttributeAssignment.kind(value))
                    }
                    static func reel(_ target: Reel?) -> Assignment {
                        .init(storageKey: "r_reel", storageValue: target)
                    }
                    static func takes(_ targets: [Take]) -> Assignment {
                        .init(storageKey: "r_takes", storageValue: Set(targets))
                    }
                }

                /// The attributes and relationships of `Shot` in their stored form, generated by `@Entity`.
                enum Columns {
                    /// The position.
                    static var order: AmphoraKit.Column<Shot, Int32> {
                        .init(key: "a_sortOrder")
                    }
                    /// The stored form of `kind`.
                    static var kind: AmphoraKit.Column<Shot, String> {
                        .init(key: "a_kind")
                    }
                    /// The `reel` relationship.
                    static var reel: AmphoraKit.Column<Shot, Reel?> {
                        .init(key: "r_reel")
                    }
                    /// The `takes` relationship.
                    static var takes: AmphoraKit.Column<Shot, Set<Take>> {
                        .init(key: "r_takes")
                    }
                }

                /// The attributes and relationships of `Shot` as stored, generated by `@Entity`: the raw
                /// value of a coded or defaulted column, a relationship as Core Data holds it.
                struct StoredValues {
                    /// The object read.
                    let object: Shot
                    /// The position.
                    var order: Int32 {
                        object.a_sortOrder
                    }
                    /// The stored form of `kind`.
                    var kind: String {
                        object.a_kind
                    }
                    /// The `reel` relationship as stored, zombies included.
                    var reel: Reel? {
                        object.r_reel
                    }
                    /// The `takes` relationship as stored, zombies included.
                    var takes: Set<Take> {
                        object.r_takes
                    }
                }

                /// The attributes and relationships as stored, for the code that copies or compares them as is.
                var stored: StoredValues {
                    StoredValues(object: self)
                }

                /// The position.
                static var order: AmphoraKit.Field<Shot, Int> {
                    .init(key: "a_sortOrder")
                }

                /// The `kind` field, for the expression form of the queries.
                static var kind: AmphoraKit.Field<Shot, Kind> {
                    .init(key: "a_kind")
                }

                /// The `reel` field, for the expression form of the queries.
                static var reel: AmphoraKit.Field<Shot, Reel?> {
                    .init(key: "r_reel")
                }

                /// The `takes` field, for the expression form of the queries.
                static var takes: AmphoraKit.Field<Shot, Set<Take>> {
                    .init(key: "r_takes")
                }
            }
            """,
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testAttributeOutsideAnEntityIsRejected() {
        assertMacroExpansion(
            """
            final class Shot: NSManagedObject {
                @Attribute var name: String
            }
            """,
            expandedSource: """
            final class Shot: NSManagedObject {
                var name: String
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Attribute' requires '@Entity' on the enclosing class, which declares the storage", line: 2, column: 5)
            ],
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testPrivateStorageAccessKeepsTheStorageInTheClassBody() throws {
        let source = Parser.parse(source: """
            @Entity(attributePrefix: "a_", storageAccess: .private)
            public final class Take: NSManagedObject {
                @Attribute var mood: String
            }
            """)
        let classDecl = try XCTUnwrap(source.statements.first?.item.as(ClassDeclSyntax.self))
        let attribute = try XCTUnwrap(classDecl.attributes.first?.as(AttributeSyntax.self))
        let members = try EntityMacro.expansion(of: attribute, providingMembersOf: classDecl, conformingTo: [], in: BasicMacroExpansionContext())
            .map(\.trimmedDescription)

        XCTAssertTrue(members.contains("@NSManaged private var a_mood: String"))
        // The stored form stays readable: `StoredValues` is nested, so it reads the private storage.
        XCTAssertTrue(members.contains { $0.contains("public var mood: String {") && $0.contains("object.a_mood") })
        XCTAssertTrue(members.contains { $0.hasSuffix("public var stored: StoredValues {\n    StoredValues(object: self)\n}") })
    }

