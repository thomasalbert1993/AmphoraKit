import XCTest
import SwiftSyntaxMacros
import SwiftSyntaxMacrosTestSupport
import AmphoraKitMacrosPlugin

final class AttributeMacroTests: XCTestCase {

    private let macros: [String: any Macro.Type] = [
        "Entity": EntityMacro.self,
        "Attribute": AttributeMacro.self,
        "Relationship": RelationshipMacro.self
    ]

    func testEntityDeclaresTheStorageAndTheMacrosTheAccessors() {
        assertMacroExpansion(
            """
            @Entity(attributePrefix: "a_", relationshipPrefix: "r_")
            final class Shot: NSManagedObject {
                /// The position.
                @Attribute("a_sortOrder", storeAs: Int32.self, access: .readWrite) var order: Int
                @Attribute(storeAs: String.self, default: Kind.wide) var kind: Kind
                @Relationship var reel: Reel?
                @Relationship var takes: [Take]
            }
            """,
            expandedSource: """
            final class Shot: NSManagedObject {
                /// The position.
                var order: Int {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_sortOrder)
                    }
                    set {
                        self.a_sortOrder = AmphoraKit.StoredAccessor.write(newValue)
                    }
                }
                var kind: Kind {
                    get {
                        AmphoraKit.StoredAccessor.read(self.a_kind, default: Kind.wide)
                    }
                }
                var reel: Reel? {
                    get {
                        AmphoraKit.StoredAccessor.read(self.r_reel)
                    }
                }
                var takes: [Take] {
                    get {
                        AmphoraKit.StoredAccessor.read(self.r_takes)
                    }
                }

                @NSManaged var a_sortOrder: Int32

                @NSManaged var a_kind: String

                @NSManaged var r_reel: Reel?

                @NSManaged var r_takes: Set<Take>

                /// The typed predicate of `Shot`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<Shot>
                    init(_ expression: AmphoraKit.QueryExpression<Shot>) {
                        self.expression = expression
                    }
                    /// The position.
                    static func order(_ match: AmphoraKit.Match<Int>) -> Query {
                        .init(.match("a_sortOrder", match))
                    }
                    /// The position.
                    static func order(_ value: Int) -> Query {
                        .order(.equal(value))
                    }
                    static func kind(_ match: AmphoraKit.Match<Kind>) -> Query {
                        .init(.match("a_kind", match))
                    }
                    static func kind(_ value: Kind) -> Query {
                        .kind(.equal(value))
                    }
                    static func reel(_ match: AmphoraKit.Match<Reel?>) -> Query {
                        .init(.match("r_reel", match))
                    }
                    static func reel(_ query: Reel.Query) -> Query {
                        .init(.relation("r_reel", query.expression))
                    }
                    static func takes(_ match: AmphoraKit.CollectionMatch<Take>) -> Query {
                        .init(.collection("r_takes", match))
                    }
                }

                /// The typed sort descriptor of `Shot`, generated by `@Entity`.
                struct Sort: AmphoraKit.EntitySort {
                    let expression: AmphoraKit.SortExpression<Shot>
                    init(_ expression: AmphoraKit.SortExpression<Shot>) {
                        self.expression = expression
                    }
                    /// The position.
                    static var order: Sort {
                        .init(key: "a_sortOrder")
                    }
                    static var kind: Sort {
                        .init(key: "a_kind")
                    }
                }

                /// The typed attribute values of `Shot`, generated by `@Entity`.
                struct Assignment: AmphoraKit.EntityAssignment {
                    typealias Root = Shot
                    let storageKey: String
                    let storageValue: Any?
                    init(storageKey: String, storageValue: Any?) {
                        self.storageKey = storageKey
                        self.storageValue = storageValue
                    }
                    /// The position.
                    static func order(_ value: Int) -> Assignment {
                        .init(storageKey: "a_sortOrder", storageValue: AmphoraKit.StoredAccessor.write(value) as Int32)
                    }
                    static func kind(_ value: Kind) -> Assignment {
                        .init(storageKey: "a_kind", storageValue: AmphoraKit.StoredAccessor.write(value) as String)
                    }
                }

                /// The position.
                static var order: AmphoraKit.Field<Shot, Int> {
                    .init(key: "a_sortOrder")
                }

                /// The `kind` field, for the expression form of the queries.
                static var kind: AmphoraKit.Field<Shot, Kind> {
                    .init(key: "a_kind")
                }

                /// The `reel` field, for the expression form of the queries.
                static var reel: AmphoraKit.Field<Shot, Reel?> {
                    .init(key: "r_reel")
                }
            }
            """,
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testAttributeOutsideAnEntityIsRejected() {
        assertMacroExpansion(
            """
            final class Shot: NSManagedObject {
                @Attribute var name: String
            }
            """,
            expandedSource: """
            final class Shot: NSManagedObject {
                var name: String
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Attribute' requires '@Entity' on the enclosing class, which declares the storage", line: 2, column: 5)
            ],
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }

    func testRelationshipNeedsAnOptionalOrAnArray() {
        assertMacroExpansion(
            """
            @Entity(relationshipPrefix: "r_")
            final class Shot: NSManagedObject {
                @Relationship var reel: Reel
            }
            """,
            expandedSource: """
            final class Shot: NSManagedObject {
                var reel: Reel

                /// The typed predicate of `Shot`, generated by `@Entity`.
                struct Query: AmphoraKit.EntityQuery {
                    let expression: AmphoraKit.QueryExpression<Shot>
                    init(_ expression: AmphoraKit.QueryExpression<Shot>) {
                        self.expression = expression
                    }
                }

                /// The typed sort descriptor of `Shot`, generated by `@Entity`.
                struct Sort: AmphoraKit.EntitySort {
                    let expression: AmphoraKit.SortExpression<Shot>
                    init(_ expression: AmphoraKit.SortExpression<Shot>) {
                        self.expression = expression
                    }
                }

                /// The typed attribute values of `Shot`, generated by `@Entity`.
                struct Assignment: AmphoraKit.EntityAssignment {
                    typealias Root = Shot
                    let storageKey: String
                    let storageValue: Any?
                    init(storageKey: String, storageValue: Any?) {
                        self.storageKey = storageKey
                        self.storageValue = storageValue
                    }
                }
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'@Relationship' expects 'Target?' for a to-one relationship or '[Target]' for a to-many one", line: 3, column: 5)
            ],
            macros: macros,
            indentationWidth: .spaces(4)
        )
    }
}
